// ToTLE reproduces, character for character and checksums included, the TLE
// CelesTrak publishes for the same element set as the GP it is given.
//
// Over 11,357 satellites it now does so for all but 12, each a B* whose JSON
// value ends in an exact 5 at the sixth digit, where the six digits the JSON
// carries cannot say which way the published value was rounded. Before #609 it
// failed for 610 on B*, 72 on eccentricity, and on every line with a zero
// second derivative, which it wrote "-0" where CelesTrak writes "+0".
func TestToTLEReproducesThePublishedTLE(t *testing.T) {
	t.Parallel()

	for _, p := range publishedGP {
		var gp GP
		if err := json.Unmarshal([]byte(p.json), &gp); err != nil {
			t.Fatalf("Unmarshal: %v", err)
		}

		line1, line2 := gp.ToTLE()

		if line1 != p.line1 {
			t.Errorf("%d line 1:\n got  %s\n want %s", gp.NoradCatID, line1, p.line1)
		}

		if line2 != p.line2 {
			t.Errorf("%d line 2:\n got  %s\n want %s", gp.NoradCatID, line2, p.line2)
		}
	}
}
